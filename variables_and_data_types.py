# 8. Variable Scope (Global vs Local)
# Variables created outside a function are Global. Variables inside are Local.
print("--- 8. Variable Scope ---")
global_score = 100     # Accessible anywhere in the file

def demonstrate_scope():
  local_score = 50     # Only accessible inside this function
  print(f"Inside function (Local): {local_score}")
  print(f"Inside function (Global): {global_score}")

demonstrate_scope()
# print(local_score) <- This would cause an Error if uncommented because it is local!
print()

# 9. Swapping Variables (The Pythonic Way)
# Exchanging values between two variables instantly without a third temporary variable
print("--- 9. Swapping Variables ---")
glass_a = "Coffee"
glass_b = "Milk"
print(f"Before Swap -> Glass A: {glass_a} | Glass B: {glass_b}")

glass_a, glass_b = glass_b, glass_a       # Swapping operation
print(f"After Swap -> Glass A: {glass_a} | Glass B: {glass_b}")
print()

# 10. Object Reference & Memory Allocation (Advanced)
# Understanding how Python shares memory addresses for collections (Lists/Dicts)
print("--- 10. Object Reference ---")
list_original = [1, 2, 3]
list_copy = list_original         # This does NOT create a new list! It points to the same memory

# Changing the copied list
list_copy.append(4)

print(f"Original List: {list_original}")        # Output: [1, 2, 3, 4] (Surprisingly changed!)
print(f"Copied List: {list_copy}")              # Output: [1, 2, 3, 4]

# The solution: Use .copy() to create a truly independent duplicate
list_true_clone = list_original.copy()
list_true_clone.append(5)

print(f"After .copy() -> Original: {list_original} | True Clone: {list_true_clone}")
print()

