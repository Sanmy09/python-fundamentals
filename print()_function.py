# 1. Escape Characters
# Demonstrating how to create new lines (\n), tabs (\t), and handle quotes
print("---1. Escape Characters---")
print("Hello everyone!\nI'm learning Python.\n\tThis text is intended using a tab.")
print("Displaying quotation marks: \"Use a backlash before the quote\"")
print()  # Empty print for spacing in the terminal

# 2. The 'sep' (Separator) Parameter
# Customizing the default space separator between multiple arguments
print("--- 2. Separator Parameter ---")
print("Day", "Month", "Year", sep="-")             # Output: Day-Month-Year
print("Alice", "Bob", "Charlie", sep=" , ")        # Output: Alice , Bob , Charlie
print("192", "168", "1", "1", sep=".")             # Output: 192.168.1.1
print()

# 3. The 'end' Parameter
# Appending a custom character at the end instead of the default newline (\n)
print("--- 3. End Parameter ---")
print("Learning Progress: 50%", end="... ")
print("Processing data", end="... ")
print("Completed!")         # These three prints stay on the same line
print()

# 4. String Formatting (f-string)
# The industry standard way to embed variables and expressions inside strings
print("--- 4. String Formatting (f-string) ---")
product_name = "ASUS Laptop"
base_price = 8500000
discount = 0.15

print(f"Product Name: {product_name}")
print(f"Base Price: Rp {base_price}")
print(f"Total Price afer 15% Discount: Rp {base_price * (1 - discount)}")
print()

# 5. Advanced f-string Formatting (Numbers & Currency)
# Formatting thousands separators and limiting decimal places
print("--- 5. Advanced f-string Formatting ---")
salary = 15000000
pi_value = 3.14159265
print(f"Currency Format: Rp {salary:,}")          # Output: Rp 15,000,000
print(f"Decimal Format: {pi_value:.2f}")          # Output: 3.14 (Rounded to 2 decimal places)
print()

# 6. The 'file' Parameter (Writing Output to a Document)
