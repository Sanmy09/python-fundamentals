# 7. The 'flush' Parameter (Forcing Instant Output)
# Forcing Python to display the text immediately without buffering (Great for animations)
print("--- 7. Flush Parameter ---")
import time

print("Loading", end="", flush=True)
for i in range(3):
  time.sleep(1)
  print(".", end="", flush=True)          # Dots appear one by one every 1 second
print()